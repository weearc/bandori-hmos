"""Select MPL standard-library bodies, retaining hashes and local changes."""
from pathlib import Path
import re,json,hashlib
ROOT=Path(__file__).resolve().parent
NAMES=['sb_reserve','sb_append','sb_init','sb_toString','runtime_getRuntime','uuid_bits','uuid_init','uuid_randomUUID','uuid_toString','uuid_msb','uuid_lsb','uuid_equals']
def generate():
 raw=(ROOT.parent/'research/lunaria-source/dvm_runtime.c').read_bytes();source=raw.decode('utf8')
 output=source[:source.index('*/')+2]+'\n/* MPL derivative generated by extract_standard_runtime.py. */\n';records=[]
 for name in NAMES:
  start=re.search(r'^static [^;\n]*?\b'+name+r'\([^;]*?\)\s*\{',source,re.M|re.S)
  if not start:raise ValueError(name)
  depth=1;end=None
  for t in re.finditer(r'''//[^\n]*|/\*.*?\*/|"(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|[{}]''',source[start.end():],re.S):
   if t.group()=='{':depth+=1
   elif t.group()=='}':
    depth-=1
    if not depth:end=start.end()+t.end();break
  body=source[start.start():end];original=body
  if name=='uuid_randomUUID':body=body.replace('RAND_bytes(', 'runtime_random_bytes(')
  if name=='sb_reserve':body=body.replace('length >= UINT32_MAX','length >= 1048576')
  if name=='sb_init':body=body.replace('   RETV();\n}', '   if (!o->utf8) { dvm__throw(vm,"java/lang/OutOfMemoryError","builder"); return false; }\n   RETV();\n}')
  if name=='uuid_init':body=body.replace('{\n','{\n   (void)out;\n',1)
  if name=='uuid_equals':body=body.replace('{\n','{\n   (void)nargs;\n',1)
  output+='\n'+body+'\n';records.append({'function':name,'source_line':source.count('\n',0,start.start())+1,'original_sha256':hashlib.sha256(original.encode()).hexdigest()})
 (ROOT/'generated/upstream_standard.inc').write_text(output,encoding='utf8')
 (ROOT/'standard-runtime-provenance.json').write_text(json.dumps({'license':'MPL-2.0','commit':'8ed4b75368153f2b9d1174c986e50c8fe87aee59','source_sha256':hashlib.sha256(raw).hexdigest(),'functions':records,'adaptations':['UUID uses OS getrandom instead of OpenSSL','Builder bounded at 1MiB and allocation failure throws','Runtime memory constant implementation deliberately excluded']},indent=2)+'\n')
if __name__=='__main__':generate()

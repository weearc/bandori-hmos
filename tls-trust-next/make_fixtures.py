"""Generate disposable local-only test certificates. Requires OpenSSL CLI."""
from pathlib import Path
import subprocess
import sys

OUT = Path(__file__).resolve().parent / "fixtures"
OUT.mkdir(exist_ok=True)

def run(*args):
    subprocess.run(["openssl", *map(str, args)], cwd=OUT, check=True,
                   stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

def root(name):
    run("req", "-x509", "-newkey", "rsa:2048", "-nodes", "-sha256",
        "-days", "3650", "-subj", f"/CN={name}",
        "-addext", "basicConstraints=critical,CA:TRUE",
        "-keyout", f"{name}.key", "-out", f"{name}.pem")

root("test-root")
root("wrong-root")
for name in ("test-root", "wrong-root"):
    run("x509", "-in", f"{name}.pem", "-outform", "DER", "-out", f"{name}.der")
for name, san, ca, expired in [
    ("valid", "DNS:local.test", "test-root", False),
    ("wrong-host", "DNS:other.test", "test-root", False),
    ("wrong-ca", "DNS:local.test", "wrong-root", False),
    ("expired", "DNS:local.test", "test-root", True),
]:
    run("req", "-newkey", "rsa:2048", "-nodes", "-sha256",
        "-subj", f"/CN={name}", "-keyout", f"{name}.key",
        "-out", f"{name}.csr")
    (OUT / f"{name}.ext").write_text(
        f"basicConstraints=critical,CA:FALSE\nkeyUsage=critical,digitalSignature,keyEncipherment\n"
        f"extendedKeyUsage=serverAuth\nsubjectAltName={san}\n", encoding="ascii")
    if expired:
        (OUT / "index.txt").write_text("", encoding="ascii")
        (OUT / "serial").write_text("1000\n", encoding="ascii")
        (OUT / "ca.cnf").write_text(
            "[ ca ]\ndefault_ca = local\n[ local ]\n"
            "database = index.txt\nserial = serial\nnew_certs_dir = .\n"
            "certificate = test-root.pem\nprivate_key = test-root.key\n"
            "default_md = sha256\npolicy = policy\ncopy_extensions = none\n"
            "[ policy ]\ncommonName = supplied\n", encoding="ascii")
        run("ca", "-batch", "-config", "ca.cnf", "-in", f"{name}.csr",
            "-out", f"{name}.pem", "-extfile", f"{name}.ext",
            "-startdate", "20200101000000Z", "-enddate", "20200102000000Z")
    else:
        run("x509", "-req", "-in", f"{name}.csr", "-CA", f"{ca}.pem",
            "-CAkey", f"{ca}.key", "-CAcreateserial", "-days", "365",
            "-sha256", "-extfile", f"{name}.ext", "-out", f"{name}.pem")
    run("x509", "-in", f"{name}.pem", "-outform", "DER", "-out", f"{name}.der")

print(f"Generated disposable fixtures in {OUT}")
print("Expected: valid + test-root + local.test succeeds with explicit CA;")
print("wrong-host rejects hostname; expired rejects time; wrong-ca and no CA reject trust.")
print("No generated root is a system trust anchor. These cannot prove system trust success.")

names = ("test-root", "wrong-root", "valid", "wrong-host", "wrong-ca", "expired")
with (Path(__file__).resolve().parent / "fixture_der.h").open("w", encoding="ascii") as header:
    header.write("/* Disposable public DER certificates. Generated by make_fixtures.py. */\n"
                 "#ifndef TLS_TRUST_FIXTURE_DER_H\n#define TLS_TRUST_FIXTURE_DER_H\n")
    for name in names:
        data = (OUT / f"{name}.der").read_bytes()
        symbol = "fixture_" + name.replace("-", "_")
        header.write(f"static const unsigned char {symbol}[] = {{\n")
        for offset in range(0, len(data), 12):
            header.write("    " + ", ".join(f"0x{byte:02x}" for byte in data[offset:offset + 12]) + ",\n")
        header.write("};\n")
    header.write("#endif\n")
